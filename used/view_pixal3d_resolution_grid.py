def content_type_for(path: Path) -> str:
    if path.suffix.lower() == ".glb":
        return GLB_MIME
    guess, _ = mimetypes.guess_type(str(path))
    return guess or "application/octet-stream"


def is_safe_child(root: Path, requested: Path) -> bool:
    try:
        requested.relative_to(root)
        return True
    except ValueError:
        return False


def compressible(path: Path, min_bytes: int) -> bool:
    suffix = path.suffix.lower()
    if suffix in ALREADY_COMPRESSED_EXTS:
        return False
    if suffix not in COMPRESS_EXTS:
        return False
    try:
        return path.stat().st_size >= min_bytes
    except OSError:
        return False


def gzip_cache_path(cache_dir: Path, rel_path: str, source: Path) -> Path:
    st = source.stat()
    key = f"{rel_path}|{st.st_mtime_ns}|{st.st_size}|gzip".encode("utf-8")
    digest = hashlib.sha256(key).hexdigest()
    return cache_dir / f"{digest}.gz"


def ensure_gzip_cache(source: Path, rel_path: str, cache_dir: Path) -> Optional[Path]:
    cache_dir.mkdir(parents=True, exist_ok=True)
    out = gzip_cache_path(cache_dir, rel_path, source)
    if out.exists() and out.stat().st_size > 0:
        return out
    tmp = out.with_suffix(out.suffix + ".tmp")
    try:
        with source.open("rb") as f_in, gzip.open(tmp, "wb", compresslevel=6) as f_out:
            shutil.copyfileobj(f_in, f_out, length=1024 * 1024)
        # If gzip is not smaller, skip it. This avoids wasting bandwidth on PNG/JPEG-like files.
        if tmp.stat().st_size >= source.stat().st_size:
            tmp.unlink(missing_ok=True)
            return None
        os.replace(tmp, out)
        return out
    except Exception:
        tmp.unlink(missing_ok=True)
        return None


def serve_asset(result_root: Path, rel_path: str, gzip_assets: bool, min_gzip_bytes: int) -> Response:
    requested = (result_root / rel_path).resolve()
    if not is_safe_child(result_root, requested):
        abort(403)
    if not requested.exists() or not requested.is_file():
        abort(404)

    content_type = content_type_for(requested)
    headers = {
        "Cache-Control": "public, max-age=604800, immutable",
        "X-Content-Type-Options": "nosniff",
    }

    accept_encoding = request.headers.get("Accept-Encoding", "")
    if gzip_assets and "gzip" in accept_encoding and compressible(requested, min_gzip_bytes):
        gz = ensure_gzip_cache(requested, rel_path, result_root / ".web_cache" / "gzip")
        if gz is not None:
            response = send_file(gz, mimetype=content_type, conditional=True)
            response.headers["Content-Encoding"] = "gzip"
            response.headers["Vary"] = "Accept-Encoding"
            response.headers.update(headers)
            return response

    response = send_from_directory(result_root, rel_path, mimetype=content_type, conditional=True)
    response.headers.update(headers)
    return response



