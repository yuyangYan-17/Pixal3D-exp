def normalize_existing_score_row(row: Dict[str, Any]) -> Dict[str, str]:
    """Normalize both the new 2-score CSV and the legacy 4-score CSV.

    Legacy mapping:
      score_1 -> overall_score
      score_2 -> local_score
    Missing or invalid scores default to 2.
    """
    overall = row.get("overall_score") or row.get("overall") or row.get("score_1") or DEFAULT_SCORE
    local = row.get("local_score") or row.get("local") or row.get("score_2") or DEFAULT_SCORE
    out = {
        "image_id": str(row.get("image_id", "") or ""),
        "input_name": str(row.get("input_name", "") or ""),
        "seed": str(row.get("seed", "") or ""),
        "pipeline_type": str(row.get("pipeline_type", "") or ""),
        "resolution": str(row.get("resolution", "") or row.get("pipeline_type", "") or "unknown"),
        "overall_score": DEFAULT_SCORE,
        "local_score": DEFAULT_SCORE,
        "updated_at": str(row.get("updated_at", "") or ""),
    }
    for key, raw in (("overall_score", overall), ("local_score", local)):
        try:
            out[key] = parse_score_value(raw)
        except Exception:
            out[key] = DEFAULT_SCORE
    return out


def ensure_score_table(path: Path, manifest: Dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    existing_rows = read_score_rows(path) if path.exists() else []
    existing_by_key = {row_key(row): row for row in existing_rows}

    aligned_rows: List[Dict[str, str]] = []
    for row in iter_manifest_score_rows(manifest):
        existing = existing_by_key.get(row_key(row))
        if existing is not None:
            row["overall_score"] = existing.get("overall_score", DEFAULT_SCORE) or DEFAULT_SCORE
            row["local_score"] = existing.get("local_score", DEFAULT_SCORE) or DEFAULT_SCORE
            row["updated_at"] = existing.get("updated_at", "")
            if existing.get("input_name"):
                row["input_name"] = existing.get("input_name", "")
            if existing.get("resolution") and row.get("resolution") in ("", "unknown"):
                row["resolution"] = existing.get("resolution", "unknown")
        aligned_rows.append(row)
    write_score_rows(path, aligned_rows)


def read_score_rows(path: Path) -> List[Dict[str, str]]:
    if not path.exists():
        return []
    with path.open("r", encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        rows: List[Dict[str, str]] = []
        for row in reader:
            norm = normalize_existing_score_row(row)
            if norm["image_id"] and norm["seed"] and norm["pipeline_type"]:
                rows.append(norm)
        rows.sort(key=lambda r: (r.get("image_id", ""), r.get("seed", ""), r.get("pipeline_type", "")))
        return rows


def write_score_rows(path: Path, rows: List[Dict[str, str]]) -> None:
    tmp = path.with_suffix(path.suffix + ".tmp")
    with tmp.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=SCORE_FIELDS)
        writer.writeheader()
        for row in rows:
            writer.writerow({field: row.get(field, DEFAULT_SCORE if field in ("overall_score", "local_score") else "") for field in SCORE_FIELDS})
    os.replace(tmp, path)


def row_key(row: Dict[str, Any]) -> Tuple[str, str, str]:
    return str(row.get("image_id", "")), str(row.get("seed", "")), str(row.get("pipeline_type", ""))


def parse_score_value(value: Any) -> str:
    ivalue = int(value)
    if ivalue not in (1, 2, 3):
        raise ValueError("score_value must be one of 1, 2, 3")
    return str(ivalue)


def summarize_scores(rows: List[Dict[str, str]]) -> Dict[str, Any]:
    by_resolution: Dict[str, Dict[str, Any]] = {}
    for row in rows:
        resolution = row.get("resolution", "") or row.get("pipeline_type", "") or "unknown"
        entry = by_resolution.setdefault(
            resolution,
            {
                "resolution": resolution,
                "count_rows": 0,
                "overall_sum": 0.0,
                "overall_count": 0,
                "local_sum": 0.0,
                "local_count": 0,
                "total_sum": 0.0,
                "total_count": 0,
            },
        )
        entry["count_rows"] += 1
        per_row_values: List[float] = []
        for field, sum_key, count_key in (
            ("overall_score", "overall_sum", "overall_count"),
            ("local_score", "local_sum", "local_count"),
        ):
            try:
                value = float(parse_score_value(row.get(field, DEFAULT_SCORE)))
            except Exception:
                value = float(DEFAULT_SCORE)
            entry[sum_key] += value
            entry[count_key] += 1
            per_row_values.append(value)
        entry["total_sum"] += sum(per_row_values) / len(per_row_values)
        entry["total_count"] += 1

    clean: Dict[str, Dict[str, Any]] = {}
    for resolution, entry in by_resolution.items():
        overall_count = entry["overall_count"]
        local_count = entry["local_count"]
        total_count = entry["total_count"]
        clean[resolution] = {
            "resolution": resolution,
            "count_rows": entry["count_rows"],
            "overall_avg": None if overall_count == 0 else entry["overall_sum"] / overall_count,
            "local_avg": None if local_count == 0 else entry["local_sum"] / local_count,
            "total_avg": None if total_count == 0 else entry["total_sum"] / total_count,
            "overall_count": overall_count,
            "local_count": local_count,
        }
    return {"by_resolution": clean}


def upsert_score(score_table_path: Path, payload: Dict[str, Any]) -> Tuple[Dict[str, str], Dict[str, Any]]:
    image_id = str(payload.get("image_id", "")).strip()
    seed = str(payload.get("seed", "")).strip()
    pipeline_type = str(payload.get("pipeline_type", "")).strip()
    resolution = str(payload.get("resolution", "") or pipeline_type or "unknown")
    if not image_id or not seed or not pipeline_type:
        raise ValueError("image_id, seed, and pipeline_type are required")

    score_key = str(payload.get("score_key", "")).strip()
    if score_key not in SCORE_KEYS:
        # Backward-compatible fallback for the temporary score_index frontend/API.
        score_index = int(payload.get("score_index", 0) or 0)
        if score_index == 1:
            score_key = "overall"
        elif score_index == 2:
            score_key = "local"
        else:
            raise ValueError("score_key must be 'overall' or 'local'")
    score_value = parse_score_value(payload.get("score_value"))

    rows = read_score_rows(score_table_path)
    target_key = (image_id, seed, pipeline_type)
    row = None
    for existing in rows:
        if row_key(existing) == target_key:
            row = existing
            break
    if row is None:
        row = {field: "" for field in SCORE_FIELDS}
        row.update({
            "image_id": image_id,
            "input_name": str(payload.get("input_name", "") or ""),
            "seed": seed,
            "pipeline_type": pipeline_type,
            "resolution": resolution,
            "overall_score": DEFAULT_SCORE,
            "local_score": DEFAULT_SCORE,
        })
        rows.append(row)
    else:
        if payload.get("input_name"):
            row["input_name"] = str(payload.get("input_name") or "")
        row["resolution"] = resolution or row.get("resolution", "unknown")

    row[f"{score_key}_score"] = score_value
    row["updated_at"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    rows.sort(key=lambda r: (r.get("image_id", ""), r.get("seed", ""), r.get("pipeline_type", "")))
    write_score_rows(score_table_path, rows)
    return row, summarize_scores(rows)

def create_app(result_root: Path, prefetch_pages: int, prefetch_meshes: bool, gzip_assets: bool, min_gzip_bytes: int, score_table_path: Path) -> Flask:
    result_root = result_root.resolve()
    manifest = load_manifest(result_root)
    score_table_path = score_table_path.resolve()
    score_lock = threading.Lock()
    ensure_score_table(score_table_path, manifest)
    app = Flask(__name__)

    @app.route("/")
    def index():
        return render_template_string(
            HTML,
            manifest_json=json.dumps(manifest, ensure_ascii=False),
            prefetch_pages_json=json.dumps(max(0, int(prefetch_pages))),
            prefetch_meshes_json=json.dumps(bool(prefetch_meshes)),
            server_compression_json=json.dumps(bool(gzip_assets)),
            score_table_path_json=json.dumps(str(score_table_path)),
        )

    @app.route("/api/manifest")
    def api_manifest():
        return jsonify(manifest)

    @app.route("/api/scores")
    def api_scores():
        with score_lock:
            rows = read_score_rows(score_table_path)
            return jsonify({"rows": rows, "summary": summarize_scores(rows), "score_table": str(score_table_path)})

    @app.route("/api/score", methods=["POST"])
    def api_score():
        payload = request.get_json(force=True, silent=False) or {}
        try:
            with score_lock:
                row, summary = upsert_score(score_table_path, payload)
            return jsonify({"ok": True, "row": row, "summary": summary})
        except Exception as exc:
            return jsonify({"ok": False, "error": str(exc)}), 400

    @app.route("/api/scores/export")
    def api_scores_export():
        with score_lock:
            ensure_score_table(score_table_path, manifest)
        return send_file(score_table_path, mimetype="text/csv", as_attachment=True, download_name=score_table_path.name)

    @app.route("/files/<path:rel_path>")
    def files(rel_path: str):
        return serve_asset(result_root, rel_path, gzip_assets=gzip_assets, min_gzip_bytes=min_gzip_bytes)

    return app


